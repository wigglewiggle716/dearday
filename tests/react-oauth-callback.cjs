'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'..','next-app','components','auth-page.jsx'),'utf8');
const client=fs.readFileSync(path.join(__dirname,'..','next-app','lib','auth-client.js'),'utf8');
const locales=fs.readFileSync(path.join(__dirname,'..','next-app','lib','locales.js'),'utf8');
assert.match(source,/signInWithOAuth\(/);
assert.match(source,/redirectTo:window\.location\.origin\+loginPath\}/);
assert.doesNotMatch(source,/redirectTo:window\.location\.origin\+loginPath\+"\?oauth=1"/);
assert.match(source,/callbackFragment\.has\("error_code"\)/);
assert.match(client,/detectSessionInUrl:true,flowType:"pkce"/);
assert.match(client,/readCurrentAccount\(client\)/);
assert.match(locales,/\["auth", "auth"\]/);
assert.match(source,/finishSignIn\(client,requested\)/);
console.log('PASS: Google OAuth redirects to stable localised login path and uses PKCE session verification');
